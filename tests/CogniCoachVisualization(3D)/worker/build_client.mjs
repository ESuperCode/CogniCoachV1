// Builds dist/motion-compiler.js (the compiler + motion database for the browser viewer).
//   node build_client.mjs
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
await build({
  entryPoints: ["src/client.js"], bundle: true, minify: true, format: "iife", globalName: "CogniCoachMotion",
  outfile: "dist/motion-compiler.js", target: "es2019", legalComments: "none",
  banner: { js: "/* CogniCoach motion compiler - generated by worker/build_client.mjs from worker/src; do not edit. */" },
});
// Web Worker wrapper: the 3D viewer compiles animations off its main thread (no frame hitch).
writeFileSync("dist/compile-worker.js", `/* CogniCoach compile worker - generated by worker/build_client.mjs; do not edit. */
importScripts("motion-compiler.js");
self.onmessage = function (e) {
  var d = e.data || {};
  try {
    var payload = CogniCoachMotion.compilePlan(d.plan, d.side);
    self.postMessage({ id: d.id, ok: true, payload: payload });
  } catch (err) {
    self.postMessage({ id: d.id, ok: false, error: (err && err.message) || String(err) });
  }
};
`);
console.log("wrote dist/motion-compiler.js and dist/compile-worker.js");
